// Helper functions to get cascading data
export const getDivisions = (): string[] => {
  return bangladeshGeoData.map(d => d.name);
};

export const getDistricts = (divisionName: string): string[] => {
  const division = bangladeshGeoData.find(d => d.name === divisionName);
  return division ? division.districts.map(d => d.name) : [];
};

export const getUpazilas = (divisionName: string, districtName: string): string[] => {
  const division = bangladeshGeoData.find(d => d.name === divisionName);
  if (!division) return [];
  
  const district = division.districts.find(d => d.name === districtName);
  return district ? district.upazilas.map(u => u.name) : [];
};
